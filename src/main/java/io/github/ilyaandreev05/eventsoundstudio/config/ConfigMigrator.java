package io.github.ilyaandreev05.eventsoundstudio.config;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/** Small, lossless fixes for known persisted-default mistakes. */
public final class ConfigMigrator {
    public static final int CURRENT_SCHEMA_VERSION = 6;
    private ConfigMigrator(){}

    /** Upgrades persisted settings and archives while keeping event audio fail-closed. */
    public static boolean migrateToCurrentSchema(Map<String,Object> root, boolean addDefaultBindings) {
        return migrateToCurrentSchema(root, addDefaultBindings, null);
    }

    /** App-store migrations may inspect the installed built-in asset before replacing its default binding. */
    public static boolean migrateToCurrentSchema(Map<String,Object> root, boolean addDefaultBindings, Path dataDirectory) {
        int version = root.get("schema_version") instanceof Number n ? n.intValue() : -1;
        if (version < 1 || version > CURRENT_SCHEMA_VERSION) return false;
        boolean changed = false;
        if (version < 3) {
            root.put("schema_version", 3);
            changed |= migrateKnownDefaults(root, addDefaultBindings);
            version = 3;
            changed = true;
        }
        if (version < 4) {
            Map<String,Object> settings = mutableMap(root.get("settings"));
            String formerOutput = settings.get("output") instanceof String output ? output : "system_default";
            String previewOutput = hasSpecificPreviewOutput(formerOutput) ? formerOutput : activeProfileOutput(root);
            if (!usablePreviewOutput(previewOutput)) previewOutput = "system_default";
            settings.putIfAbsent("preview_output", previewOutput);
            settings.put("output", io.github.ilyaandreev05.eventsoundstudio.audio.MixerOutputSelector.AUDIO_MATRIX_EVENTS);
            root.put("settings", settings);
            for (Map<String,Object> profile : maps(root.get("profiles")))
                profile.put("output", io.github.ilyaandreev05.eventsoundstudio.audio.MixerOutputSelector.AUDIO_MATRIX_EVENTS);
            for (Map<String,Object> binding : maps(root.get("bindings")))
                binding.put("output", "profile_default");
            root.put("schema_version", 4);
            changed = true;
        }
        if (version < 5) {
            if (addDefaultBindings) EventPresetMigration.apply(root);
            root.put("schema_version", 5);
            changed = true;
            version = 5;
        }
        if (version < 6) {
            if (addDefaultBindings) changed |= StandardClickMigration.apply(root, dataDirectory);
            root.put("schema_version", 6);
            changed = true;
        }
        return changed;
    }

    private static boolean isEventOutput(String value) {
        return io.github.ilyaandreev05.eventsoundstudio.audio.MixerOutputSelector.AUDIO_MATRIX_EVENTS.equals(value);
    }

    private static boolean usablePreviewOutput(String value) {
        return value != null && !value.isBlank() && !isEventOutput(value);
    }

    private static boolean hasSpecificPreviewOutput(String value) {
        return usablePreviewOutput(value) && !"system_default".equals(value);
    }

    private static String activeProfileOutput(Map<String,Object> root) {
        Object activeId = root.get("active_profile");
        for (Map<String,Object> profile : maps(root.get("profiles"))) {
            if (String.valueOf(activeId).equals(profile.get("id")) && profile.get("output") instanceof String output)
                return output;
        }
        return null;
    }

    @SuppressWarnings("unchecked") private static Map<String,Object> mutableMap(Object value) {
        return value instanceof Map<?,?> map ? (Map<String,Object>) map : new java.util.LinkedHashMap<>();
    }

    /** Rewrites the exact malformed letter-group generated by early Event Sound Studio defaults. */
    public static boolean migrateKnownDefaults(Map<String,Object> root){
        return migrateKnownDefaults(root,true);
    }

    /** Archive packages can contain only a selected subset, so they must not gain new default bindings. */
    public static boolean migrateKnownDefaults(Map<String,Object> root,boolean addDefaultBindings){
        boolean changed=false;
        Object rawGroups=root.get("groups");
        if(rawGroups instanceof List<?> groups){List<String> oldMembers=new ArrayList<>();for(char c='A';c<='Z';c++)oldMembers.add("KEY_A"+c);
            for(Object item:groups)if(item instanceof Map<?,?> raw&&"builtin.letters".equals(raw.get("id"))&&oldMembers.equals(raw.get("members"))){@SuppressWarnings("unchecked") Map<String,Object> group=(Map<String,Object>)raw;group.put("members",DefaultConfig.BUILTIN_GROUPS.get("builtin.letters"));changed=true;}}
        Object rawSettings=root.get("settings");if(rawSettings instanceof Map<?,?> settingsRaw){@SuppressWarnings("unchecked") Map<String,Object> settings=(Map<String,Object>)settingsRaw;Object click=settings.get("mouse_click_policy");if(click instanceof Map<?,?> clickRaw&&"immediate_plus_double".equals(clickRaw.get("mode"))&&number(clickRaw.get("double_click_window_ms"),250)==250){@SuppressWarnings("unchecked") Map<String,Object> policy=(Map<String,Object>)clickRaw;policy.put("mode","wait_and_suppress");changed=true;}}
        Object rawBindings=root.get("bindings");Object rawProfiles=root.get("profiles");if(rawBindings instanceof List<?> bindingList&&rawProfiles instanceof List<?> profileList){
            @SuppressWarnings("unchecked") List<Map<String,Object>> bindings=(List<Map<String,Object>>)bindingList;
            Map<String,Object> defaults=DefaultConfig.create();List<Map<String,Object>> defaultBindings=maps(defaults.get("bindings"));
            for(String id:addDefaultBindings?List.of("super-key-press"):List.<String>of()){
                Map<String,Object> defaultBinding=defaultBindings.stream().filter(item->id.equals(item.get("id"))).findFirst().orElse(null);if(defaultBinding==null)continue;
                String event=String.valueOf(defaultBinding.get("event"));boolean exists=bindings.stream().anyMatch(item->id.equals(item.get("id"))||event.equals(item.get("event")));
                if(!exists){
                    bindings.add(copyMap(defaultBinding));changed=true;
                    for(Object item:profileList)if(item instanceof Map<?,?> profileRaw){@SuppressWarnings("unchecked") Map<String,Object> profile=(Map<String,Object>)profileRaw;if(!"desk".equals(profile.get("id")))continue;Object enabledRaw=profile.get("enabled_bindings");if(enabledRaw instanceof List<?> enabledList){List<Object> enabled=new ArrayList<>(enabledList);if(!enabled.contains(id)){enabled.add(id);profile.put("enabled_bindings",enabled);}}}
                }
            }
            Map<String,Integer> durations=Map.of("all-key-press",45,"letters-default",45,"mouse-click",45,"wheel-up",28,"wheel-down",28,"wheel-left",28,"wheel-right",28,"workspace-change",450,"super-key-press",220);
            for(Map<String,Object> binding:bindings)if(durations.containsKey(String.valueOf(binding.get("id")))&&number(binding.get("duration_ms"),0)==0){binding.put("duration_ms",durations.get(String.valueOf(binding.get("id"))));changed=true;}
        }
        return changed;
    }
    @SuppressWarnings("unchecked") private static List<Map<String,Object>> maps(Object value){return value instanceof List<?> list?(List<Map<String,Object>>)list:List.of();}
    private static Map<String,Object> copyMap(Map<String,Object> value){Map<String,Object> result=new java.util.LinkedHashMap<>();value.forEach((key,item)->result.put(key,item instanceof Map<?,?> nested?copyNested(nested):item instanceof List<?> list?new ArrayList<>(list):item));return result;}
    private static Map<String,Object> copyNested(Map<?,?> value){Map<String,Object> result=new java.util.LinkedHashMap<>();value.forEach((key,item)->result.put(String.valueOf(key),item));return result;}
    private static double number(Object value,double fallback){return value instanceof Number number?number.doubleValue():fallback;}
}
